"""Hand-written copy for `docs/screen-map.md` (phone-verify map, ticket 03). Read by
`tools/screen_map.py`, which fails if this and the code disagree.

**What goes here:** a human name and one line on each screen, the reach steps the code cannot work
out by itself, the controls worth knowing, and the voice tools that open it. **What does not:**
anything the code already says. A route, its file, its header text and its test tags are read from
the code; an edge whose label sits beside `onClick = onOpenX` in the parent screen is read from the
code too, so most Settings screens carry no `reach` here at all.

**The repo is public.** Selectors are the app's own fixed strings. Never put a vault label, a memory,
an amount, a merchant or a person's name in this file.

Step kinds, for `reach` and `controls`:

- `("text", "Memory")`: a node whose text is exactly that (case and spacing ignored)
- `("desc", "Settings")`: a node whose content description is exactly that
- `("desc", "Chat with ^")`: a trailing `^` means "starts with" - for strings with a name in them
- `("tag", "vault-message")`: a Compose test tag, shown as resource-id with `testTagsAsResourceId`
- `("key", "BACK")`: a key event

`controls` entries are `(kind, value, why)`. A control whose words say send, pay, buy, delete,
forget, ship or install is refused by `tools/phone tap` unless Kevin said yes in chat; listing it
here documents it, it does not make it tappable.
"""

