"""The Alfred pack: a versioned bundle of Alfred's wording the engine serves (alfred-ota ticket 01).

`packs/alfred.yaml` is GENERATED by `gen_pack.py` from `shared_clauses.txt` (the clauses every
assistant shares) plus `packs/alfred.source.yaml` (the version and everything only the pack
has). This module is the one reader: `load_pack(text)` validates a pack and refuses a bad one in
words, `current()` reads the committed file once per process. `GET /api/assistant/pack`
(`assistant/pack_views.py`) serves what `current()` returns, and the generator runs every pack
it writes through `load_pack` first, so a file the engine would refuse is never written.

**The locked set (map decision 2, Kevin 2026-11-05).** A compromised engine must not be able to
talk Alfred out of the crisis route, the safety rules, the honesty clause, the ask-before rule
(pay, send, post, delete, book) or the never-type-passwords rule. Those are compiled into the
app; the phone ignores them in a pack (ticket 02), and the engine refuses to load a pack that
names any of them, as a clause, a tool override or a flag, in any letter case. The two rules
that had no constant name anywhere are named here: `ASK_BEFORE` and `NO_PASSWORDS`.

**Two hashes, named for what they cover.** `content_sha256` is the wording alone (no version);
`packs/alfred.lock` records it beside the version, so a test catches wording that changed while
the version stood still. `sha256` covers the whole served payload, version included, and is the
endpoint's ETag, so a bumped version is always a new ETag.

No Django import, on purpose: `gen_pack.py` runs from a bare checkout, as
`gen_shared_clauses.py` does.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
PACKS_DIR = HERE / "packs"
PACK_FILE = PACKS_DIR / "alfred.yaml"

# Compiled into the app, never overridable by a pack. Compared upper-cased.
LOCKED_NAMES: frozenset[str] = frozenset(
    {"CRISIS", "SAFETY_INSTRUCTIONS", "CANNOT_CLAUSE", "ASK_BEFORE", "NO_PASSWORDS"}
)

# The served JSON, canonically serialised, may not exceed this.
MAX_BYTES = 64 * 1024

KEYS = ("version", "clauses", "tool_text", "flags", "extra_rules")
CONTENT_KEYS = KEYS[1:]
TOOL_TEXT_KEYS = frozenset({"description", "result_prefix"})


class PackError(Exception):
    """A pack the engine refuses to load. The message says why, in words."""


def canonical(value) -> bytes:
    """One byte string per value: sorted keys, no whitespace, UTF-8. Both hashes and the size
    cap are taken over this, so they never depend on how the YAML happened to be laid out."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode(
        "utf-8"
    )


def _sha256(value) -> str:
    return hashlib.sha256(canonical(value)).hexdigest()


@dataclass(frozen=True)
class Pack:
    version: int
    clauses: dict[str, str]
    tool_text: dict[str, dict[str, str]]
    flags: dict[str, bool | int]
    extra_rules: list[str]
    sha256: str = field(init=False)
    content_sha256: str = field(init=False)

    def __post_init__(self):
        object.__setattr__(self, "content_sha256", _sha256(self.content()))
        object.__setattr__(self, "sha256", _sha256({"version": self.version, **self.content()}))

    def content(self) -> dict:
        return {
            "clauses": self.clauses,
            "tool_text": self.tool_text,
            "flags": self.flags,
            "extra_rules": self.extra_rules,
        }

    def payload(self) -> dict:
        """What `GET /api/assistant/pack` answers with."""
        return {"version": self.version, "sha256": self.sha256, **self.content()}


def _require_mapping(value, where: str) -> dict:
    if not isinstance(value, dict):
        raise PackError(f"`{where}` must be a mapping, not {type(value).__name__}.")
    for key in value:
        if not isinstance(key, str) or not key.strip():
            raise PackError(f"`{where}` has a key that is not a name: {key!r}.")
    return value


def _refuse_locked(names, where: str) -> None:
    locked = sorted(name for name in names if name.upper() in LOCKED_NAMES)
    if locked:
        raise PackError(
            f"`{where}` names {', '.join(locked)}, which the app keeps compiled in and no pack "
            f"may override (the locked set: {', '.join(sorted(LOCKED_NAMES))})."
        )


def build_pack(data) -> Pack:
    """Validate a parsed pack and return it, or raise `PackError` saying what is wrong."""
    data = _require_mapping(data, "pack")
    missing = [k for k in KEYS if k not in data]
    extra = sorted(set(data) - set(KEYS))
    if missing or extra:
        raise PackError(
            "A pack has exactly the keys "
            + ", ".join(KEYS)
            + (f"; missing {', '.join(missing)}" if missing else "")
            + (f"; unknown {', '.join(extra)}" if extra else "")
            + "."
        )

    version = data["version"]
    if isinstance(version, bool) or not isinstance(version, int) or version < 1:
        raise PackError(f"`version` must be a whole number from 1 up, not {version!r}.")

    clauses = _require_mapping(data["clauses"], "clauses")
    _refuse_locked(clauses, "clauses")
    for name, text in clauses.items():
        if not (name.isidentifier() and name.isupper()):
            raise PackError(f"Clause name {name!r} must be UPPER_SNAKE, as in shared_clauses.txt.")
        if not isinstance(text, str) or not text.strip():
            raise PackError(f"Clause {name} has no text.")

    tool_text = _require_mapping(data["tool_text"], "tool_text")
    _refuse_locked(tool_text, "tool_text")
    for tool, override in tool_text.items():
        override = _require_mapping(override, f"tool_text.{tool}")
        unknown = sorted(set(override) - TOOL_TEXT_KEYS)
        if unknown or not override:
            raise PackError(
                f"`tool_text.{tool}` may set only {', '.join(sorted(TOOL_TEXT_KEYS))}"
                + (f", not {', '.join(unknown)}" if unknown else ", and sets neither")
                + "."
            )
        for key, text in override.items():
            if not isinstance(text, str) or not text.strip():
                raise PackError(f"`tool_text.{tool}.{key}` has no text.")

    flags = _require_mapping(data["flags"], "flags")
    _refuse_locked(flags, "flags")
    for name, value in flags.items():
        if not isinstance(value, (bool, int)):
            raise PackError(f"Flag {name} must be true, false or a whole number, not {value!r}.")

    extra_rules = data["extra_rules"]
    if not isinstance(extra_rules, list):
        raise PackError("`extra_rules` must be a list of short rules.")
    for i, rule in enumerate(extra_rules):
        if not isinstance(rule, str) or not rule.strip():
            raise PackError(f"`extra_rules` entry {i + 1} has no text.")

    pack = Pack(
        version=version,
        clauses=dict(clauses),
        tool_text={k: dict(v) for k, v in tool_text.items()},
        flags=dict(flags),
        extra_rules=list(extra_rules),
    )
    size = len(canonical(pack.payload()))
    if size > MAX_BYTES:
        raise PackError(f"The pack serialises to {size} bytes; the cap is {MAX_BYTES}.")
    return pack


def load_pack(text: str) -> Pack:
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise PackError(f"The pack is not valid YAML: {exc}") from exc
    return build_pack(data)


@lru_cache(maxsize=1)
def current() -> Pack:
    """The committed pack, read once per process. A deploy is the only way it changes (map
    decision 1), so there is nothing to invalidate. Raises `PackError` (and caches nothing) if the
    file is refused."""
    return load_pack(PACK_FILE.read_text(encoding="utf-8"))
