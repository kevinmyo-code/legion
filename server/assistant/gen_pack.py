"""Generate `packs/alfred.yaml` and keep `packs/alfred.lock` honest (alfred-ota ticket 01).

    python server/assistant/gen_pack.py           # write alfred.yaml
    python server/assistant/gen_pack.py --check   # exit 1 if alfred.yaml or the lock is stale
    python server/assistant/gen_pack.py --lock    # record the version and content hash

**Where each part comes from.** The clauses are `shared_clauses.txt`'s (parsed by
`gen_shared_clauses.parse`, the same parse the web prompt is built from, so the web prompt and
the pack cannot drift), less the locked set (`pack.LOCKED_NAMES`), plus any pack-only clauses in
`packs/alfred.source.yaml`. Everything else (the version, `tool_text`, `flags`, `extra_rules`) is
hand-edited in that source file. Edit the source or `shared_clauses.txt`, never `alfred.yaml`.

**The lock.** `alfred.lock` holds the version and `content_sha256` (the wording, no version).
`tests/test_assistant_pack.py` fails when they disagree with `alfred.yaml`. Changing the wording
means: bump `version` in the source, run this script, then `--lock`. `--lock` refuses when the
wording changed and the version did not, or when the version went backwards, so the check
cannot be satisfied by re-locking alone.

Stand-alone like `gen_shared_clauses.py`: no Django import.
"""

from __future__ import annotations

import sys
from pathlib import Path

if __package__ in (None, ""):  # run as a script: make `assistant` importable
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import yaml  # noqa: E402

from assistant import gen_shared_clauses  # noqa: E402
from assistant.pack import (  # noqa: E402
    LOCKED_NAMES,
    PACK_FILE,
    PACKS_DIR,
    Pack,
    PackError,
    build_pack,
)

SOURCE = PACKS_DIR / "alfred.source.yaml"
LOCK_FILE = PACKS_DIR / "alfred.lock"

HEADER = (
    "# GENERATED by `server/assistant/gen_pack.py` from `shared_clauses.txt` and\n"
    "# `packs/alfred.source.yaml`. Do not edit: edit those, bump the version, regenerate, then\n"
    "# `gen_pack.py --lock`. Served by GET /api/assistant/pack.\n"
)


def build(shared_source: str, pack_source: str) -> Pack:
    """The pack the two sources describe, validated exactly as the engine will load it."""
    source = yaml.safe_load(pack_source)
    if not isinstance(source, dict):
        raise PackError(f"{SOURCE.name} must be a mapping.")
    own = source.get("clauses") or {}
    if not isinstance(own, dict):
        raise PackError(f"`clauses` in {SOURCE.name} must be a mapping.")
    shared = {
        c.name: c.text
        for c in gen_shared_clauses.parse(shared_source)
        if c.name not in LOCKED_NAMES
    }
    clash = sorted(set(own) & set(shared))
    if clash:
        raise PackError(
            f"{SOURCE.name} defines {', '.join(clash)}, which shared_clauses.txt already owns. "
            f"Edit it there, so the web prompt changes with it."
        )
    return build_pack({**source, "clauses": {**shared, **own}})


def render(pack: Pack) -> str:
    body = yaml.safe_dump(
        {"version": pack.version, **pack.content()},
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )
    return HEADER + body


def read_lock(text: str | None) -> tuple[int, str] | None:
    if text is None:
        return None
    data = yaml.safe_load(text) or {}
    return int(data["version"]), str(data["content_sha256"])


def render_lock(pack: Pack) -> str:
    return (
        "# Written by `gen_pack.py --lock`. The version and the hash of the wording it names;\n"
        "# tests/test_assistant_pack.py fails when alfred.yaml disagrees.\n"
        f"version: {pack.version}\n"
        f"content_sha256: {pack.content_sha256}\n"
    )


def lock_problem(pack: Pack, lock: tuple[int, str] | None) -> str | None:
    """Why the lock does not vouch for this pack, in words, or None when it does."""
    if lock is None:
        return f"{LOCK_FILE.name} is missing. Run: python server/assistant/gen_pack.py --lock"
    version, content_sha256 = lock
    if pack.version < version:
        return (
            f"The pack's version went backwards ({version} locked, {pack.version} now). "
            f"Versions only go up."
        )
    if pack.version == version and pack.content_sha256 != content_sha256:
        return (
            f"The pack's wording changed but its version is still {version}. Bump `version` in "
            f"{SOURCE.name}, run gen_pack.py, then gen_pack.py --lock."
        )
    if pack.version > version:
        return (
            f"The version is {pack.version} but the lock still records {version}. "
            f"Run: python server/assistant/gen_pack.py --lock"
        )
    return None


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.exists() else None


def current_build() -> Pack:
    return build(
        gen_shared_clauses.SOURCE.read_text(encoding="utf-8"), SOURCE.read_text(encoding="utf-8")
    )


def main(argv: list[str]) -> int:
    try:
        pack = current_build()
    except (PackError, gen_shared_clauses.SourceError) as exc:
        print(f"Refused, nothing written: {exc}")
        return 1
    rendered = render(pack)
    on_disk = _read(PACK_FILE)
    lock = read_lock(_read(LOCK_FILE))

    if "--check" in argv:
        problems = []
        if on_disk != rendered:
            problems.append(f"{PACK_FILE.name} is stale. Run: python server/assistant/gen_pack.py")
        if problem := lock_problem(pack, lock):
            problems.append(problem)
        for line in problems:
            print(line)
        if not problems:
            print(f"{PACK_FILE.name} and {LOCK_FILE.name} match version {pack.version}.")
        return 1 if problems else 0

    if "--lock" in argv:
        problem = lock_problem(pack, lock)
        if lock is not None and problem and pack.version <= lock[0]:
            print(f"Refused, lock unchanged: {problem}")
            return 1
        LOCK_FILE.write_text(render_lock(pack), encoding="utf-8", newline="\n")
        print(f"Locked version {pack.version} ({pack.content_sha256[:12]}).")

    if on_disk != rendered:
        PACK_FILE.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"Wrote {PACK_FILE.name} (version {pack.version}).")
    elif "--lock" not in argv:
        print(f"{PACK_FILE.name} already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
