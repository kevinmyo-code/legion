"""Independent known-answer vectors for the car link (pairing + MNAI2).

Written from the protocol document (.legion/reports/headunit-link-protocol-1120.md, revision 2),
NOT from the Kotlin: it shares no code with the head unit or the phone. Uses the `cryptography`
package (pip install cryptography). Every input is fixed, so the output is deterministic; run

    python make_vectors.py > vectors.json

and commit both files. Gradle never runs this; the Kotlin tests only read vectors.json.
All values are made up (no real key, token, place or person).
"""
import hashlib
import hmac
import json
import struct

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF


def hkdf(ikm, salt, info, length=32):
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=salt if salt else b"\x00" * 32, info=info).derive(ikm)


def mac(key, msg):
    return hmac.new(key, msg, hashlib.sha256).digest()


def nonce(dir4, ctr):
    assert len(dir4) == 4
    return dir4 + struct.pack(">Q", ctr)


def seal(key, n, aad, pt):
    return AESGCM(key).encrypt(n, pt, aad)


def pub_bytes(priv):
    nums = priv.public_key().public_numbers()
    return b"\x04" + nums.x.to_bytes(32, "big") + nums.y.to_bytes(32, "big")


H = lambda b: b.hex()

# ---------------------------------------------------------------- pairing (section 3)
unit_priv = ec.derive_private_key(0x1111111111111111111111111111111111111111111111111111111111111111, ec.SECP256R1())
phone_priv = ec.derive_private_key(0x2222222222222222222222222222222222222222222222222222222222222222, ec.SECP256R1())
unit_pk = pub_bytes(unit_priv)
phone_pk = pub_bytes(phone_priv)
secret = bytes(range(0x10, 0x20))

qr_key = hkdf(secret, b"", b"MNAI-PAIR qr v1")
salt_key = hkdf(secret, b"", b"MNAI-PAIR salt v1")
transcript = b"MNAI-PAIR" + b"\x01" + b"\x01" + unit_pk + phone_pk
z_unit = unit_priv.exchange(ec.ECDH(), phone_priv.public_key())
z_phone = phone_priv.exchange(ec.ECDH(), unit_priv.public_key())
assert z_unit == z_phone and len(z_unit) == 32
master = hkdf(z_unit, salt_key, b"MNAI-PAIR keys v1" + hashlib.sha256(transcript).digest())
link_key = hkdf(master, b"", b"MNAI-PAIR link v1")
hand_key = hkdf(master, b"", b"MNAI-PAIR handover v1")
confirm_key = hkdf(master, b"", b"MNAI-PAIR confirm v1")
check_raw = hkdf(master, b"", b"MNAI-PAIR check v1", 4)
check = str(int.from_bytes(check_raw, "big") % 1_000_000).zfill(6)

hello_mac = mac(qr_key, b"MNAI-PAIR hello v1" + b"\x01" + unit_pk + phone_pk)
ack_kc = mac(confirm_key, b"MNAI-PAIR unit confirm v1" + transcript)
ok = b'{"ok":true}'
code_ok = seal(hand_key, nonce(b"CDOK", 1), b"MNAI-PAIR code ok v1", ok)
handover_pt = b'{"v":1,"engine_token":"test-token","engine_user_id":"u-1","phone_name":"Test phone"}'
handover = seal(hand_key, nonce(b"HAND", 1), b"MNAI-PAIR handover v1", handover_pt)
done = seal(hand_key, nonce(b"DONE", 1), b"MNAI-PAIR done v1", ok)
stored = seal(hand_key, nonce(b"STOR", 1), b"MNAI-PAIR stored v1", ok)

# ---------------------------------------------------------------- MNAI2 (section 4)
p2u = hkdf(link_key, b"", b"MNAI2 loc phone->unit v1")
u2p = hkdf(link_key, b"", b"MNAI2 loc unit->phone v1")


def datagram(dir_key, dir4, typ, session, counter, body):
    header = b"MNAI2" + b"\x01" + typ + session + struct.pack(">Q", counter)
    key = hkdf(dir_key, session, b"MNAI2 session v1")
    return header + seal(key, nonce(dir4, counter), header, body)


unit_session = bytes([0xA0 + i for i in range(16)])
phone_session = bytes([0xB0 + i for i in range(16)])
challenge = bytes([0xC0 + i for i in range(8)])

hello_body = struct.pack(">I", 1000) + challenge
hello = datagram(u2p, b"U2P ", b"H", unit_session, 7, hello_body)


def fix_body(age):
    # flags: acc | bearing | speed | alt | bearingAcc | speedAcc
    return (challenge + struct.pack(">H", 63) + struct.pack(">dd", 1.5, -2.25) +
            struct.pack(">fff", 5.0, 90.0, 20.0) + struct.pack(">d", 15.0) +
            struct.pack(">I", age) + struct.pack(">ff", 2.0, 0.5))


fix = datagram(p2u, b"P2U ", b"F", phone_session, 3, fix_body(250))
fix_max_age = datagram(p2u, b"P2U ", b"F", phone_session, 4, fix_body(0xFFFFFFFF))
zone = datagram(p2u, b"P2U ", b"Z", phone_session, 5, challenge + b"Etc/UTC")
revoke = datagram(p2u, b"P2U ", b"R", phone_session, 6, challenge)

print(json.dumps({
    "note": "Generated by make_vectors.py from the protocol document; independent of the Kotlin. Made-up values.",
    "pairing": {
        "unit_private_scalar": "1111111111111111111111111111111111111111111111111111111111111111",
        "phone_private_scalar": "2222222222222222222222222222222222222222222222222222222222222222",
        "unit_pk": H(unit_pk), "phone_pk": H(phone_pk), "secret": H(secret),
        "qr_key": H(qr_key), "salt_key": H(salt_key), "transcript": H(transcript), "z": H(z_unit),
        "master": H(master), "link_key": H(link_key), "hand_key": H(hand_key), "confirm_key": H(confirm_key),
        "check": check, "hello_mac": H(hello_mac), "ack_kc": H(ack_kc),
        "code_ok": H(code_ok), "handover_plain": handover_pt.decode(), "handover": H(handover),
        "done": H(done), "stored": H(stored),
    },
    "mnai2": {
        "p2u_key": H(p2u), "u2p_key": H(u2p),
        "unit_session": H(unit_session), "phone_session": H(phone_session), "challenge": H(challenge),
        "hello": {"counter": 7, "interval_ms": 1000, "bytes": H(hello)},
        "fix": {"counter": 3, "lat": 1.5, "lng": -2.25, "age_ms": 250, "bytes": H(fix)},
        "fix_max_age": {"counter": 4, "age_ms": 0xFFFFFFFF, "bytes": H(fix_max_age)},
        "zone": {"counter": 5, "zone": "Etc/UTC", "bytes": H(zone)},
        "revoke": {"counter": 6, "bytes": H(revoke)},
    },
}, indent=2))
