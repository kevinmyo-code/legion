-- Lists redesign slice 1a: drop the two legacy list tables.
--
-- DESTRUCTIVE. This deletes rows. On prod (read 2026-11-24, read-only, via a
-- READ ONLY transaction in `manage.py shell` on the legion-worker job) that is
-- `item_lists` = 1 row and `list_items` = 26 rows. Nothing else.
--
-- Why they can go:
--   * The phone repointed every live read and write onto `events` in
--     backend-erp ticket 15 step 4, and retired the legacy Supabase sync that
--     pushed and pulled these two tables in this same slice.
--   * The engine never had a viewset, a route or a reader for either one. The
--     `legacy.ItemList`/`legacy.ListItem` models were removed in this slice's
--     code commit; `read_list` reads `events` and `checklists`, not these.
--   * Neither table is in the pytest schema mirror
--     (`tests/legacy_test_schema.py`), so no test has ever written one.
--
-- ORDER MATTERS: `list_items.list_origin_guid` is a foreign key against
-- `item_lists.origin_guid` (not its primary key - see
-- `household/tenancy_sql.py`'s own note on why that unique index had to stay
-- server-wide). The child goes first, so neither drop needs CASCADE and
-- nothing outside these two tables can be reached by this change.
--
-- RUN THIS ONLY AFTER both of these are live, or a running client writes a
-- table that no longer exists:
--   1. the engine deploy carrying this slice, and
--   2. the phone OTA carrying the sync retirement. An installed phone from
--      before that build still backfills and pulls both tables, and still
--      subscribes a Supabase Realtime channel to each.
--
-- The Room tables of the same names on the phone are NOT touched by this and
-- are not dropped at all: Room is additive only (CLAUDE.md section 5), and
-- `EngineDataMigrationWave1` still reads the phone's `list_items` on a stale
-- install.

drop table if exists public.list_items;
drop table if exists public.item_lists;
