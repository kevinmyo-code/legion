"""Known-answer vector for the protocol revision 8 hand-over (engine_vehicle_id and mapbox_token).

Written from the protocol document (3.3, 3.4, 3.5 rev 8), with the same fixed inputs and the same
primitives as the head unit branch's make_vectors.py; it shares no code with the Kotlin. Run

    python make_vectors_rev8.py > vectors-rev8.json

Gradle never runs this; the Kotlin tests only read vectors-rev8.json. All values are made up.
"""
import hashlib
import json

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF


def hkdf(ikm, salt, info, length=32):
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=salt if salt else b"\x00" * 32, info=info).derive(ikm)


def pub_bytes(priv):
    nums = priv.public_key().public_numbers()
    return b"\x04" + nums.x.to_bytes(32, "big") + nums.y.to_bytes(32, "big")


unit_priv = ec.derive_private_key(0x1111111111111111111111111111111111111111111111111111111111111111, ec.SECP256R1())
phone_priv = ec.derive_private_key(0x2222222222222222222222222222222222222222222222222222222222222222, ec.SECP256R1())
unit_pk = pub_bytes(unit_priv)
phone_pk = pub_bytes(phone_priv)
secret = bytes(range(0x10, 0x20))

salt_key = hkdf(secret, b"", b"MNAI-PAIR salt v1")
transcript = b"MNAI-PAIR" + b"\x01" + b"\x01" + unit_pk + phone_pk
z = unit_priv.exchange(ec.ECDH(), phone_priv.public_key())
master = hkdf(z, salt_key, b"MNAI-PAIR keys v1" + hashlib.sha256(transcript).digest())
hand_key = hkdf(master, b"", b"MNAI-PAIR handover v1")

# 3.5: compact JSON, the phone's field order, blank fields omitted (engine_vehicle_id after engine_user_id).
plain = (b'{"v":1,"engine_token":"test-token","engine_user_id":"u-1",'
         b'"engine_vehicle_id":"vehicle-id-for-tests","mapbox_token":"pk.map-token-for-tests",'
         b'"phone_name":"Test phone"}')
nonce = b"HAND" + (1).to_bytes(8, "big")
sealed = AESGCM(hand_key).encrypt(nonce, plain, b"MNAI-PAIR handover v1")

print(json.dumps({
    "note": "Generated by make_vectors_rev8.py from the protocol document (3.5 rev 8); same fixed inputs as vectors.json. Made-up values.",
    "hand_key": hand_key.hex(),
    "handover_rev8_plain": plain.decode(),
    "handover_rev8": sealed.hex(),
}, indent=2))
